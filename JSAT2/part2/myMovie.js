// Create the myMovie object as an object literal
const myMovie = {
  title: "The longest day",
  year: 1964
};

// Print the myMovie object to the console
console.log("myMovie object:", myMovie);

// Add new properties to the existing myMovie object
myMovie.rating = 5;
myMovie.summary = "World War II movie about the Normandy landings";

// Print the myMovie object to the console with the new properties
console.log("myMovie object:", myMovie);

// Change the rating and year properties
myMovie.rating = 4;
myMovie.year = 1962;

// Print the myMovie object to the console with the updated properties
console.log("myMovie object with updated rating and year:", myMovie);
